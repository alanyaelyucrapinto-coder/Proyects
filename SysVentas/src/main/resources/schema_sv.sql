ALTER TABLE ArticuloFunerario ADD COLUMN IF NOT EXISTS material VARCHAR(100) DEFAULT 'Madera Seleccionada';

CREATE TABLE IF NOT EXISTS Venta (
    idVenta     VARCHAR(10) PRIMARY KEY,
    dniCliente  VARCHAR(8) NOT NULL,
    fechaVenta  DATE NOT NULL,
    netoTotal   DECIMAL(10, 2) NOT NULL,
    igv         DECIMAL(10, 2) NOT NULL,
    precioTotal DECIMAL(10, 2) NOT NULL,
    idUsuario   VARCHAR(5) NOT NULL,
    CONSTRAINT fk_venta_cliente FOREIGN KEY (dniCliente) REFERENCES Cliente (idDNI),
    CONSTRAINT fk_venta_usuario FOREIGN KEY (idUsuario) REFERENCES Usuario (idUsuario)
);

CREATE TABLE IF NOT EXISTS VentaDetalla (
    idVentaDetal VARCHAR(10) PRIMARY KEY,
    idVenta      VARCHAR(10) NOT NULL,
    idDefuncion  BIGINT NOT NULL,
    idArticulo   BIGINT,
    descripcion  VARCHAR(200),
    precioUnit   DECIMAL(10, 2) NOT NULL,
    porceUtil    DECIMAL(5, 2) NOT NULL,
    cantidad     INTEGER NOT NULL,
    netoTotal    DECIMAL(10, 2) NOT NULL,
    CONSTRAINT fk_ventadetalla_venta FOREIGN KEY (idVenta) REFERENCES Venta (idVenta),
    CONSTRAINT fk_ventadetalla_defuncion FOREIGN KEY (idDefuncion) REFERENCES Defunciones (id)
);

CREATE TABLE IF NOT EXISTS vent_carrito (
    id_carrito      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dniCliente      VARCHAR(8) NOT NULL,
    idDefuncion     BIGINT NOT NULL,
    idArticulo      BIGINT,
    nombreFallecido VARCHAR(200) NOT NULL,
    precioUnit      DECIMAL(10, 2) NOT NULL,
    porceUtil       DECIMAL(5, 2) NOT NULL,
    cantidad        INTEGER NOT NULL,
    netoTotal       DECIMAL(10, 2) NOT NULL,
    estado          INTEGER NOT NULL,
    idUsuario       VARCHAR(5) NOT NULL,
    CONSTRAINT fk_carrito_defuncion FOREIGN KEY (idDefuncion) REFERENCES Defunciones (id),
    CONSTRAINT fk_carrito_usuario FOREIGN KEY (idUsuario) REFERENCES Usuario (idUsuario)
);

