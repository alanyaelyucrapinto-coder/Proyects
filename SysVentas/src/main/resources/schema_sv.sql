-- Esquema H2 idempotente para IntelliJ IDEA (JavaFX) - Padrón de Defunciones y Venta de Ataúdes y Flores

CREATE TABLE IF NOT EXISTS Parentesco (
    idParentesco INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS CausaMuerte (
    idCausa VARCHAR(5) PRIMARY KEY,
    nombre  VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS Defunciones (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombreFallecido VARCHAR(100) NOT NULL,
    fechaDefuncion  DATE NOT NULL,
    lugarDefuncion  VARCHAR(150) NOT NULL,
    idCausa         VARCHAR(5) NOT NULL,
    nombreFamiliar  VARCHAR(100) NOT NULL,
    idParentesco    INTEGER NOT NULL,
    CONSTRAINT fk_defunciones_causa FOREIGN KEY (idCausa) REFERENCES CausaMuerte (idCausa),
    CONSTRAINT fk_defunciones_parentesco FOREIGN KEY (idParentesco) REFERENCES Parentesco (idParentesco)
);

CREATE TABLE IF NOT EXISTS Perfil (
    idPerfil VARCHAR(5) PRIMARY KEY,
    nombre   VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS Usuario (
    idUsuario VARCHAR(5) PRIMARY KEY,
    usuario   VARCHAR(50) NOT NULL,
    clave     VARCHAR(100) NOT NULL,
    idPerfil  VARCHAR(5) NOT NULL,
    CONSTRAINT fk_usuario_perfil FOREIGN KEY (idPerfil) REFERENCES Perfil (idPerfil)
);

CREATE TABLE IF NOT EXISTS Cliente (
    idDNI     VARCHAR(8) PRIMARY KEY,
    nombre    VARCHAR(100) NOT NULL,
    direccion VARCHAR(150),
    celular   VARCHAR(15)
);

CREATE TABLE IF NOT EXISTS ArticuloFunerario (
    idArticulo  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo        VARCHAR(20) NOT NULL,
    nombre      VARCHAR(100) NOT NULL,
    tamano      VARCHAR(80) NOT NULL,
    material    VARCHAR(100) NOT NULL,
    precioUnit  DECIMAL(10, 2) NOT NULL,
    porceUtil   DECIMAL(5, 2) NOT NULL,
    stock       INTEGER NOT NULL
);

